"use client";

import Image from "next/image";
import Link from "next/link";
import { useRouter } from "next/navigation";
import { useEffect, useMemo, useState } from "react";
import { ConfirmDialog } from "@/components/dialog";
import { Icon } from "@/components/icons";
import { Uploader } from "@/components/teacher/uploader";
import { useToast } from "@/components/toast";
import { api } from "@/lib/api-client";
import { CATEGORY_ICONS, categoryIcon, type CategoryIcon } from "@/lib/categories";
import type { CategoryDTO } from "@/services/categories";
import type { CategoryCourseOption } from "./load";

type Category = CategoryDTO & { courseIds: string[] };

interface Draft {
  name: string;
  description: string;
  label: string;
  icon: CategoryIcon;
  published: boolean;
  courseIds: string[];
}

const draftOf = (c: Category | null): Draft => ({
  name: c?.name ?? "",
  description: c?.description ?? "",
  label: c?.label ?? "",
  icon: (CATEGORY_ICONS as readonly string[]).includes(c?.icon ?? "") ? (c!.icon as CategoryIcon) : "book",
  published: c?.published ?? true,
  courseIds: c?.courseIds ?? [],
});

const comparable = (d: Draft) => JSON.stringify({ ...d, courseIds: [...d.courseIds].sort() });

function Section({ title, hint, children }: { title: string; hint?: string; children: React.ReactNode }) {
  return (
    <section className="card p-5 sm:p-6">
      <h2 className="font-bold text-ink">{title}</h2>
      {hint && <p className="mt-0.5 text-sm text-muted">{hint}</p>}
      <div className="mt-4 space-y-4">{children}</div>
    </section>
  );
}

/** Creates (initial = null) or edits one learning category, including which courses are filed under it. */
export function CategoryEditor({ initial, courses, canUpload }: { initial: Category | null; courses: CategoryCourseOption[]; canUpload: boolean }) {
  const router = useRouter();
  const toast = useToast();
  const isNew = !initial;
  const [saved, setSaved] = useState(() => draftOf(initial));
  const [d, setD] = useState(() => draftOf(initial));
  const [errors, setErrors] = useState<Record<string, string | undefined>>({});
  const [busy, setBusy] = useState(false);
  const [confirm, setConfirm] = useState<"image" | "category" | null>(null);
  const [confirmBusy, setConfirmBusy] = useState(false);
  const [confirmError, setConfirmError] = useState<string | null>(null);
  const [removedImage, setRemovedImage] = useState<string | undefined>();
  const imageUrl = initial?.imageUrl && initial.imageUrl !== removedImage ? initial.imageUrl : undefined;
  const dirty = useMemo(() => comparable(d) !== comparable(saved), [d, saved]);

  useEffect(() => {
    if (!dirty) return;
    const warn = (e: BeforeUnloadEvent) => e.preventDefault();
    window.addEventListener("beforeunload", warn);
    return () => window.removeEventListener("beforeunload", warn);
  }, [dirty]);

  function set<K extends keyof Draft>(key: K, value: Draft[K]) {
    setD((x) => ({ ...x, [key]: value }));
    if (errors[key]) setErrors((e) => ({ ...e, [key]: undefined }));
  }

  async function save() {
    const found: Record<string, string> = {};
    if (d.name.trim().length < 2) found.name = "Enter a category name";
    setErrors(found);
    if (Object.keys(found).length) return toast("Please fix the highlighted fields.", "error");

    setBusy(true);
    // The category's URL (?category=…) is generated by the server from the first name and never changes.
    const body = d;
    const res = isNew ? await api<{ category: Category }>("/api/teacher/categories", { body }) : await api<{ category: Category }>(`/api/teacher/categories/${initial!.id}`, { method: "PUT", body });
    setBusy(false);
    if (!res.ok) {
      if (res.error.fields) setErrors(Object.fromEntries(Object.entries(res.error.fields).map(([k, v]) => [k, v?.[0]])));
      return toast(res.error.message, "error");
    }
    const next = draftOf(res.data.category);
    setSaved(next);
    setD(next);
    if (isNew) {
      toast(`${res.data.category.name} created. You can now upload a card image.`);
      router.replace(`/admin/categories/${res.data.category.id}`);
    } else {
      toast(res.data.category.published ? "Category saved. The homepage shows the change now." : "Category saved (hidden from visitors).");
      router.refresh();
    }
  }

  async function runConfirm() {
    if (!initial) return;
    setConfirmBusy(true);
    setConfirmError(null);
    const res = await api<{ uncategorized?: number }>(confirm === "image" ? `/api/teacher/categories/${initial.id}/image` : `/api/teacher/categories/${initial.id}`, { method: "DELETE" });
    setConfirmBusy(false);
    if (!res.ok) return setConfirmError(res.error.message);
    if (confirm === "image") {
      setRemovedImage(imageUrl);
      setConfirm(null);
      toast("Image removed.");
      router.refresh();
    } else {
      const moved = res.data.uncategorized ?? 0;
      toast(moved ? `${initial.name} deleted. ${moved} course${moved === 1 ? " is" : "s are"} now without a category.` : `${initial.name} deleted.`);
      router.push("/admin/categories");
      router.refresh();
    }
  }

  const err = (k: string) => (errors[k] ? <p className="mt-1 text-xs text-red-700">{errors[k]}</p> : null);
  const toggleCourse = (id: string) => set("courseIds", d.courseIds.includes(id) ? d.courseIds.filter((c) => c !== id) : [...d.courseIds, id]);
  const currentSlug = initial?.slug;

  return (
    <form
      noValidate
      onSubmit={(e) => {
        e.preventDefault();
        save();
      }}
      className="grid gap-6 xl:grid-cols-[1fr_320px]"
    >
      <div className="space-y-6">
        <Section title="Card content" hint="Shown on the homepage “What would you like to learn?” cards and as a catalogue filter.">
          <div>
            <label htmlFor="c-name" className="label">
              Name <span className="text-red-600">*</span>
            </label>
            <input id="c-name" className="input" value={d.name} maxLength={60} onChange={(e) => set("name", e.target.value)} aria-invalid={errors.name ? true : undefined} autoFocus={isNew} placeholder="e.g. Web Development" />
            {err("name")}
          </div>
          <div>
            <div className="flex items-baseline justify-between">
              <label htmlFor="c-desc" className="label">
                Short description
              </label>
              <span className="text-xs text-muted">{d.description.length}/300</span>
            </div>
            <textarea id="c-desc" rows={3} className="input" value={d.description} maxLength={300} onChange={(e) => set("description", e.target.value)} placeholder="What students learn in this path, in one or two sentences." />
          </div>
          <div>
            <label htmlFor="c-label" className="label">
              Badge (optional)
            </label>
            <input id="c-label" className="input max-w-xs" value={d.label} maxLength={30} onChange={(e) => set("label", e.target.value)} placeholder="e.g. Most popular, New" />
          </div>
          <fieldset>
            <legend className="label">Icon</legend>
            <div className="flex flex-wrap gap-2">
              {CATEGORY_ICONS.map((icon) => (
                <label key={icon} className={`flex size-11 cursor-pointer items-center justify-center rounded-xl border transition has-[:focus-visible]:ring-2 has-[:focus-visible]:ring-brand-300 ${d.icon === icon ? "border-brand-600 bg-brand-600 text-white" : "border-line bg-white text-brand-700 hover:border-brand-200"}`} title={icon}>
                  <input type="radio" name="icon" value={icon} checked={d.icon === icon} onChange={() => set("icon", icon)} className="sr-only" aria-label={`Icon: ${icon}`} />
                  <Icon name={icon} className="size-5" />
                </label>
              ))}
            </div>
            <p className="mt-1 text-xs text-muted">Shown when no card image is uploaded, and on course cards in this category.</p>
          </fieldset>
        </Section>

        <Section title="Courses in this category" hint="Ticked courses are filed under this category; a course belongs to one category at a time. Only published courses are shown to visitors.">
          {courses.length === 0 ? (
            <p className="text-sm text-muted">
              No courses yet.{" "}
              <Link href="/admin/courses/new" className="font-semibold text-brand-600 hover:underline">
                Create a course
              </Link>
            </p>
          ) : (
            <ul className="grid gap-2 sm:grid-cols-2">
              {courses.map((c) => {
                const on = d.courseIds.includes(c.id);
                const elsewhere = c.category && c.category !== currentSlug ? (c.categoryName ?? c.category) : undefined;
                return (
                  <li key={c.id}>
                    <label className={`flex cursor-pointer items-center gap-3 rounded-lg border p-3 text-sm transition ${on ? "border-brand-500 bg-brand-50" : "border-line hover:border-brand-200"}`}>
                      <input type="checkbox" className="size-4 accent-brand-600" checked={on} onChange={() => toggleCourse(c.id)} />
                      <span className="min-w-0 flex-1">
                        <span className="block truncate font-medium text-ink">{c.title}</span>
                        {elsewhere && <span className="block text-xs text-muted">{on ? `Moves here from “${elsewhere}”` : `In “${elsewhere}”`}</span>}
                      </span>
                      {!c.published && <span className="badge bg-slate-100 text-slate-700">Draft</span>}
                    </label>
                  </li>
                );
              })}
            </ul>
          )}
        </Section>
      </div>

      <aside className="space-y-6 xl:sticky xl:top-24 xl:self-start">
        <section className="card overflow-hidden">
          <p className="border-b border-line px-4 py-3 text-xs font-bold tracking-wider text-muted uppercase">Homepage card preview</p>
          <div className="bg-canvas p-4">
            <div className="flex flex-col rounded-2xl border border-line bg-white p-4">
              <span className="flex items-start justify-between gap-3">
                <span className="flex size-11 items-center justify-center rounded-xl bg-brand-50 text-brand-700">
                  <Icon name={categoryIcon(d.icon)} className="size-5" />
                </span>
                {d.label && <span className="rounded-full bg-sun-50 px-2 py-0.5 text-[11px] font-bold text-sun-700">{d.label}</span>}
              </span>
              <span className="mt-3 font-display text-base font-bold text-ink">{d.name || "Category name"}</span>
              <span className="mt-1 line-clamp-2 text-sm text-muted">{d.description || "Short description"}</span>
            </div>
          </div>
          <div className="relative aspect-[16/7] bg-gradient-to-br from-night-800 via-brand-800 to-night-900">
            {imageUrl ? (
              <Image src={imageUrl} alt="Category card image" fill sizes="320px" className="object-cover" />
            ) : (
              <div className="flex h-full items-center justify-center text-white/70">
                <Icon name={categoryIcon(d.icon)} className="size-10" />
              </div>
            )}
          </div>
          <div className="space-y-3 p-4">
            <p className="text-sm font-semibold text-ink">Card image (optional)</p>
            {isNew ? (
              <p className="text-xs text-muted">Save the category first, then upload an image.</p>
            ) : !canUpload ? (
              <p className="text-xs text-sun-700">Uploads are unavailable until Cloudinary is configured.</p>
            ) : (
              <>
                <Uploader kind="category_image" targetId={initial!.id} label={imageUrl ? "Replace image" : "Upload image"} onDone={() => router.refresh()} />
                <p className="text-xs text-muted">Square JPG, PNG or WebP. Shown on the homepage subject box instead of the icon.</p>
                {imageUrl && (
                  <button type="button" className="text-xs font-semibold text-red-700 hover:underline" onClick={() => setConfirm("image")}>
                    Remove image
                  </button>
                )}
              </>
            )}
          </div>
        </section>

        <section className="card space-y-4 p-4">
          <label className="flex cursor-pointer items-start gap-3">
            <input type="checkbox" className="mt-1 size-4 accent-leaf-600" checked={d.published} onChange={(e) => set("published", e.target.checked)} />
            <span>
              <span className="block text-sm font-semibold text-ink">Published</span>
              <span className="text-xs text-muted">Show on the homepage and as a catalogue filter.</span>
            </span>
          </label>
          <button className="btn-primary w-full" disabled={busy || (!dirty && !isNew)}>
            {busy ? "Saving…" : isNew ? "Create category" : "Save changes"}
          </button>
          <p className="text-center text-xs" aria-live="polite">
            {dirty ? <span className="font-semibold text-sun-700">● Unsaved changes</span> : <span className="text-muted">{isNew ? "Not saved yet" : "All changes saved"}</span>}
          </p>
          {!isNew && (
            <div className="flex flex-col gap-2 border-t border-line pt-3 text-sm">
              {initial!.published && (
                <Link href={`/courses?category=${initial!.slug}`} className="btn-outline">
                  <Icon name="eye" /> Open in catalogue
                </Link>
              )}
              <button
                type="button"
                className="mt-1 text-xs font-semibold text-red-700 hover:underline"
                onClick={() => {
                  setConfirmError(null);
                  setConfirm("category");
                }}
              >
                Delete this category
              </button>
            </div>
          )}
        </section>
      </aside>

      <ConfirmDialog
        open={confirm !== null}
        title={confirm === "image" ? "Remove card image?" : "Delete this category?"}
        confirmLabel={confirm === "image" ? "Remove image" : "Delete category"}
        busy={confirmBusy}
        error={confirmError}
        onConfirm={runConfirm}
        onCancel={() => setConfirm(null)}
      >
        <p>{confirm === "image" ? "The image will be deleted from storage; the icon is shown instead." : `${initial?.name} will be removed from the homepage and the catalogue filters. Its courses are not deleted: they stay published, just without a category.`}</p>
      </ConfirmDialog>
    </form>
  );
}
