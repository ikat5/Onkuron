"use client";

import Link from "next/link";
import { useRouter } from "next/navigation";
import { useEffect, useMemo, useState } from "react";
import type { CourseOption } from "@/app/admin/teachers/teacher-editor";
import { ConfirmDialog } from "@/components/dialog";
import { Icon } from "@/components/icons";
import { useToast } from "@/components/toast";
import { api } from "@/lib/api-client";
import { INTERACTIVE_MODULES, MODULE_LABELS, type InteractiveModule } from "@/lib/interactive";
import type { TopicDTO } from "@/services/interactive";

interface Draft {
  title: string;
  chapter: string;
  chapterBn: string;
  glyph: string;
  /** One learning point per line. */
  learn: string;
  module: InteractiveModule | "";
  courseId: string;
  published: boolean;
}

const draftOf = (t: TopicDTO | null): Draft => ({ title: t?.title ?? "", chapter: t?.chapter ?? "", chapterBn: t?.chapterBn ?? "", glyph: t?.glyph ?? "", learn: (t?.learn ?? []).join("\n"), module: t?.module ?? "", courseId: t?.courseId ?? "", published: t?.published ?? false });

const learnList = (text: string) =>
  text
    .split("\n")
    .map((l) => l.trim())
    .filter(Boolean);

function Section({ title, hint, children }: { title: string; hint?: string; children: React.ReactNode }) {
  return (
    <section className="card p-5 sm:p-6">
      <h2 className="font-bold text-ink">{title}</h2>
      {hint && <p className="mt-0.5 text-sm text-muted">{hint}</p>}
      <div className="mt-4 space-y-4">{children}</div>
    </section>
  );
}

/** Creates (initial = null) or edits one topic of the homepage HSC ICT lab. */
export function TopicEditor({ initial, courses }: { initial: TopicDTO | null; courses: CourseOption[] }) {
  const router = useRouter();
  const toast = useToast();
  const isNew = !initial;
  const [saved, setSaved] = useState(() => draftOf(initial));
  const [d, setD] = useState(() => draftOf(initial));
  const [errors, setErrors] = useState<Record<string, string | undefined>>({});
  const [busy, setBusy] = useState(false);
  const [confirm, setConfirm] = useState(false);
  const [confirmBusy, setConfirmBusy] = useState(false);
  const dirty = useMemo(() => JSON.stringify(d) !== JSON.stringify(saved), [d, saved]);
  const learn = learnList(d.learn);

  useEffect(() => {
    if (!dirty) return;
    const warn = (e: BeforeUnloadEvent) => e.preventDefault();
    window.addEventListener("beforeunload", warn);
    return () => window.removeEventListener("beforeunload", warn);
  }, [dirty]);

  function set<K extends keyof Draft>(key: K, value: Draft[K]) {
    setD((x) => ({ ...x, [key]: value }));
    if (errors[key]) setErrors((e) => ({ ...e, [key]: undefined }));
  }

  async function save() {
    const found: Record<string, string> = {};
    if (d.title.trim().length < 3) found.title = "Use at least 3 characters";
    if (learn.length > 8) found.learn = "Use at most 8 points";
    if (learn.some((l) => l.length > 120)) found.learn = "Keep each point under 120 characters";
    setErrors(found);
    if (Object.keys(found).length) return toast("Please fix the highlighted fields.", "error");

    setBusy(true);
    // The slug is generated by the server from the first title and kept; it only identifies the tab.
    const body = { ...d, learn };
    const res = isNew ? await api<{ topic: TopicDTO }>("/api/teacher/topics", { body }) : await api<{ topic: TopicDTO }>(`/api/teacher/topics/${initial!.id}`, { method: "PUT", body });
    setBusy(false);
    if (!res.ok) {
      if (res.error.fields) setErrors(Object.fromEntries(Object.entries(res.error.fields).map(([k, v]) => [k, v?.[0]])));
      if (res.error.code === "conflict") setErrors((e) => ({ ...e, title: res.error.message }));
      return toast(res.error.message, "error");
    }
    const next = draftOf(res.data.topic);
    setSaved(next);
    setD(next);
    if (isNew) {
      toast(`“${res.data.topic.title}” created.`);
      router.replace(`/admin/interactive/${res.data.topic.id}`);
    } else {
      toast(res.data.topic.published ? "Lesson saved. The homepage shows the change now." : "Lesson saved (hidden from visitors).");
      router.refresh();
    }
  }

  async function runConfirm() {
    if (!initial) return;
    setConfirmBusy(true);
    const res = await api(`/api/teacher/topics/${initial.id}`, { method: "DELETE" });
    setConfirmBusy(false);
    if (!res.ok) return toast(res.error.message, "error");
    toast(`“${initial.title}” deleted.`);
    router.push("/admin/interactive");
    router.refresh();
  }

  const err = (k: string) => (errors[k] ? <p className="mt-1 text-xs text-red-700">{errors[k]}</p> : null);

  return (
    <form
      noValidate
      onSubmit={(e) => {
        e.preventDefault();
        save();
      }}
      className="grid gap-6 xl:grid-cols-[1fr_320px]"
    >
      <div className="space-y-6">
        <Section title="Topic" hint="Shown as a tab in the homepage HSC ICT lab and at the top of its simulation.">
          <div>
            <label htmlFor="t-title" className="label">
              Title <span className="text-red-600">*</span>
            </label>
            <input id="t-title" className="input" value={d.title} maxLength={100} onChange={(e) => set("title", e.target.value)} aria-invalid={errors.title ? true : undefined} autoFocus={isNew} placeholder="e.g. Number systems" />
            {err("title")}
          </div>
          <div className="grid gap-4 sm:grid-cols-[1fr_1.4fr_110px]">
            <div>
              <label htmlFor="t-chapter" className="label">
                Chapter
              </label>
              <input id="t-chapter" className="input" value={d.chapter} maxLength={40} onChange={(e) => set("chapter", e.target.value)} placeholder="Chapter 3" />
            </div>
            <div>
              <label htmlFor="t-chapter-bn" className="label">
                Chapter name (Bangla)
              </label>
              <input id="t-chapter-bn" className="input" value={d.chapterBn} maxLength={80} onChange={(e) => set("chapterBn", e.target.value)} placeholder="সংখ্যা পদ্ধতি ও ডিজিটাল ডিভাইস" />
            </div>
            <div>
              <label htmlFor="t-glyph" className="label">
                Tab symbol
              </label>
              <input id="t-glyph" className="input font-mono" value={d.glyph} maxLength={6} onChange={(e) => set("glyph", e.target.value)} placeholder="A·B" />
            </div>
          </div>
          <div>
            <label htmlFor="t-learn" className="label">
              What students will understand
            </label>
            <textarea id="t-learn" rows={4} className="input" value={d.learn} onChange={(e) => set("learn", e.target.value)} placeholder={"Truth tables\nDe Morgan's theorems"} aria-invalid={errors.learn ? true : undefined} />
            {errors.learn ? err("learn") : <p className="mt-1 text-xs text-muted">One point per line, up to 8.</p>}
          </div>
        </Section>

        <Section title="Learning experience" hint="Connect the topic to its simulation and to the course that teaches it in full.">
          <div>
            <label htmlFor="t-module" className="label">
              Interactive simulation
            </label>
            <select id="t-module" className="input" value={d.module} onChange={(e) => set("module", e.target.value as Draft["module"])}>
              <option value="">None yet — show “being prepared”</option>
              {INTERACTIVE_MODULES.map((m) => (
                <option key={m} value={m}>
                  {MODULE_LABELS[m]}
                </option>
              ))}
            </select>
          </div>
          <div>
            <label htmlFor="t-course" className="label">
              Linked course (optional)
            </label>
            <select id="t-course" className="input" value={d.courseId} onChange={(e) => set("courseId", e.target.value)} aria-invalid={errors.courseId ? true : undefined}>
              <option value="">No course — link to the HSC ICT catalogue</option>
              {courses.map((c) => (
                <option key={c.id} value={c.id}>
                  {c.title}
                  {c.published ? "" : " (draft)"}
                </option>
              ))}
            </select>
            {errors.courseId ? err("courseId") : <p className="mt-1 text-xs text-muted">The lab&apos;s “Learn this in HSC ICT” button opens this course once it&apos;s published.</p>}
          </div>
        </Section>
      </div>

      <aside className="space-y-6 xl:sticky xl:top-24 xl:self-start">
        <section className="card p-4">
          <p className="label">Tab preview</p>
          <div className="flex items-center gap-3 rounded-2xl border border-brand-600 bg-brand-600 p-2.5 pr-3 text-white shadow-lift">
            <span className="flex size-10 shrink-0 items-center justify-center rounded-xl bg-sun-500 font-mono text-sm font-bold text-ink">{d.glyph || d.title.slice(0, 1).toUpperCase() || "?"}</span>
            <span className="min-w-0">
              <span className="block text-sm leading-tight font-bold">{d.title || "Topic title"}</span>
              {d.chapter && <span className="mt-0.5 block text-[11px] text-brand-100">{d.chapter}</span>}
            </span>
          </div>
          <p className="mt-3 text-xs text-muted">{d.module ? `Runs the ${MODULE_LABELS[d.module]}.` : "No simulation chosen: the lab shows “being prepared” for this topic."}</p>
        </section>

        <section className="card space-y-4 p-4">
          <label className="flex cursor-pointer items-start gap-3">
            <input type="checkbox" className="mt-1 size-4 accent-leaf-600" checked={d.published} onChange={(e) => set("published", e.target.checked)} />
            <span>
              <span className="block text-sm font-semibold text-ink">Published</span>
              <span className="text-xs text-muted">Show this topic in the homepage HSC ICT lab.</span>
            </span>
          </label>
          <button className="btn-primary w-full" disabled={busy || (!dirty && !isNew)}>
            {busy ? "Saving…" : isNew ? "Create lesson" : "Save changes"}
          </button>
          <p className="text-center text-xs" aria-live="polite">
            {dirty ? <span className="font-semibold text-sun-700">● Unsaved changes</span> : <span className="text-muted">{isNew ? "Not saved yet" : "All changes saved"}</span>}
          </p>
          {!isNew && (
            <div className="flex flex-col gap-2 border-t border-line pt-3 text-sm">
              <Link href="/#interactive-learning" className="btn-outline">
                <Icon name="eye" /> View on the homepage
              </Link>
              <button type="button" className="mt-1 text-xs font-semibold text-red-700 hover:underline" onClick={() => setConfirm(true)}>
                Delete this lesson
              </button>
            </div>
          )}
        </section>
      </aside>

      <ConfirmDialog open={confirm} title="Delete this interactive lesson?" confirmLabel="Delete lesson" busy={confirmBusy} onConfirm={runConfirm} onCancel={() => setConfirm(false)}>
        <p>“{initial?.title}” will be removed from the homepage HSC ICT lab. To hide it temporarily, unpublish it instead.</p>
      </ConfirmDialog>
    </form>
  );
}
